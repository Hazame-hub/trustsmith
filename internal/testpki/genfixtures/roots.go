package main

import (
	"crypto/x509"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/Hazame-hub/trustsmith/internal/testpki"
)

// rootsFixtures writes the explicitly supplied trust-anchor files used by the
// trust evaluation tests into out. Anchors are taken from committed corpus
// files, so they match the committed certificates. Like the corpus, existing
// files are kept unless force is set.
func rootsFixtures(corpus, out string, force bool, pemOf func(ders ...[]byte) []byte) {
	if err := os.MkdirAll(out, 0o755); err != nil {
		log.Fatal(err)
	}
	files := map[string]string{}
	written := 0
	write := func(name, description string, data []byte) {
		files[name] = description
		path := filepath.Join(out, name)
		if _, err := os.Stat(path); err == nil && !force {
			return
		}
		if err := os.WriteFile(path, data, 0o644); err != nil {
			log.Fatal(err)
		}
		written++
	}
	certsOf := func(name string, want int) [][]byte {
		c := loadCertificates(filepath.Join(corpus, name))
		if len(c) != want {
			log.Fatalf("%s must hold %d certificates; found %d", name, want, len(c))
		}
		return c
	}

	bundle := certsOf("bundle.pem", 3)
	write("test-root.pem", "the root CA of bundle.pem", pemOf(bundle[2]))
	write("intermediate-as-anchor.pem", "the intermediate CA of bundle.pem, supplied as a (non-self-signed) anchor", pemOf(bundle[1]))
	write("unrelated-root.pem", "a self-signed root CA that issued nothing in the corpus",
		pemOf(testpki.Issue(f, testpki.Template{
			CommonName: "Trustsmith Test Unrelated Root CA", Organization: "Trustsmith Tests", Serial: 2000,
			NotBefore: date(2026, 1, 1), NotAfter: date(2036, 1, 1),
			IsCA: true, MaxPathLen: -1, KeyUsage: x509.KeyUsageCertSign | x509.KeyUsageCRLSign,
		}, testpki.ECDSAKey(f), nil).DER))
	write("legacy-signing-ca.pem", "the RSA CA of sha1-with-issuer.pem", pemOf(certsOf("sha1-with-issuer.pem", 2)[1]))
	cross := certsOf("path-cross-signed.pem", 5)
	write("path-cross-roots.pem", "root A and root B of path-cross-signed.pem", pemOf(cross[2], cross[4]))
	write("path-expired-root.pem", "the root CA of path-expired-intermediate.pem", pemOf(certsOf("path-expired-intermediate.pem", 3)[2]))
	write("tls-endpoint-root.pem", "the root CA of tls-endpoint.pem, the in-process TLS endpoint's chain", pemOf(certsOf("tls-endpoint.pem", 3)[2]))
	write("purpose-root.pem", "the root CA of the purpose fixtures (purpose-root-ca.pem)", pemOf(certsOf("purpose-root-ca.pem", 1)[0]))
	write("with-private-key.pem", "the root of bundle.pem followed by a private key block (refused, never decoded)",
		append(pemOf(bundle[2]), rfc8410TestKey...))
	write("empty.pem", "zero bytes (refused: a roots file needs a certificate)", nil)
	write("malformed.pem", "a single corrupt certificate block (refused)",
		[]byte("-----BEGIN CERTIFICATE-----\nthis block is !!! not base64\n-----END CERTIFICATE-----\n"))

	names := make([]string, 0, len(files))
	for n := range files {
		names = append(names, n)
	}
	sort.Strings(names)
	var readme strings.Builder
	readme.WriteString("# Trust-anchor files\n\nGenerated by `go run ./internal/testpki/genfixtures`; do not edit by hand.\n")
	readme.WriteString("Files supplied with `trustsmith inspect --roots` in the trust evaluation tests.\n\n| File | Contents |\n|---|---|\n")
	for _, n := range names {
		fmt.Fprintf(&readme, "| `%s` | %s |\n", n, files[n])
	}
	if err := os.WriteFile(filepath.Join(out, "README.md"), []byte(readme.String()), 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("roots has %d files; wrote %d to %s\n", len(names), written, out)
}
